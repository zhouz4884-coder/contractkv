#!/usr/bin/env python3
"""Build and audit the minimal IEEE TSC manuscript submission package."""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import zipfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SUBMISSION = ROOT / "submission"
FIGURES = {
    "fig1_contractkv_visio.png": ROOT / "Paper" / "figures" / "fig1_contractkv_visio.png",
    "fig2_global_benefit.pdf": ROOT / "Paper" / "figures" / "fig2_global_benefit.pdf",
    "fig3_llama_baselines.pdf": ROOT / "Paper" / "figures" / "fig3_llama_baselines.pdf",
    "fig4_verification_economics.pdf": ROOT
    / "Paper"
    / "figures"
    / "fig4_verification_economics.pdf",
    "fig5_service_locality.pdf": ROOT / "Paper" / "figures" / "fig5_service_locality.pdf",
    "fig6_operating_region.pdf": ROOT / "Paper" / "figures" / "fig6_operating_region.pdf",
}
TEXT_FORBIDDEN = re.compile(
    r"(?i)\b(chatgpt|codex|claude|gemini|ai-generated|generated by)\b|"
    r"\.codex|\.qoder|created_by"
)
COMPILE_INTERMEDIATE_SUFFIXES = {".aux", ".log", ".out"}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def copy_required(source: Path, target: Path) -> None:
    if not source.is_file():
        raise FileNotFoundError(source)
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, target)


def audit_text(path: Path) -> list[str]:
    if path.suffix.lower() not in {".tex", ".txt", ".md", ".csv", ".json"}:
        return []
    text = path.read_text(encoding="utf-8", errors="replace")
    return [match.group(0) for match in TEXT_FORBIDDEN.finditer(text)]


def build_package(date_tag: str) -> tuple[Path, Path]:
    package_name = f"contractkv_tsc_submission_{date_tag}"
    package_root = SUBMISSION / "package" / package_name
    archive_path = SUBMISSION / f"{package_name}.zip"
    if package_root.exists():
        shutil.rmtree(package_root)
    if archive_path.exists():
        archive_path.unlink()
    package_root.mkdir(parents=True)

    copy_required(SUBMISSION / "contractkv_tsc.tex", package_root / "contractkv_tsc.tex")
    copy_required(SUBMISSION / "contractkv_tsc.pdf", package_root / "contractkv_tsc.pdf")
    copy_required(
        SUBMISSION / "contractkv_supplement.tex",
        package_root / "contractkv_supplement.tex",
    )
    copy_required(
        SUBMISSION / "contractkv_supplement.pdf",
        package_root / "contractkv_supplement.pdf",
    )
    for name, source in FIGURES.items():
        copy_required(source, package_root / "figures" / name)

    readme = (
        "ContractKV IEEE Transactions on Services Computing submission\n\n"
        "Contents:\n"
        "- contractkv_tsc.pdf: 12-page manuscript\n"
        "- contractkv_tsc.tex: self-contained LaTeX source\n"
        "- contractkv_supplement.pdf: current-vLLM relevance audit\n"
        "- contractkv_supplement.tex: supplementary source\n"
        "- figures/: files referenced by the manuscript\n\n"
        "Build the manuscript and supplement with two pdflatex passes each. "
        "The bibliography is embedded in the manuscript source. Full "
        "reproducibility artifacts are available at "
        "https://github.com/zhouz4884-coder/contractkv.\n"
    )
    (package_root / "README.txt").write_text(readme, encoding="utf-8")

    forbidden_hits: dict[str, list[str]] = {}
    for path in sorted(package_root.rglob("*")):
        if path.is_file():
            if path.suffix.lower() in COMPILE_INTERMEDIATE_SUFFIXES:
                raise RuntimeError(f"compile intermediate in package: {path}")
            hits = audit_text(path)
            if hits:
                forbidden_hits[path.relative_to(package_root).as_posix()] = hits
    if forbidden_hits:
        raise RuntimeError(f"forbidden package text: {forbidden_hits}")

    files = [path for path in sorted(package_root.rglob("*")) if path.is_file()]
    sums = "\n".join(
        f"{sha256(path)}  {path.relative_to(package_root).as_posix()}"
        for path in files
    )
    (package_root / "SHA256SUMS.txt").write_text(sums + "\n", encoding="ascii")

    with zipfile.ZipFile(archive_path, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(package_root.rglob("*")):
            if path.is_file():
                archive.write(path, f"{package_name}/{path.relative_to(package_root)}")
    archive_path.with_suffix(".zip.sha256").write_text(
        f"{sha256(archive_path)}  {archive_path.name}\n", encoding="ascii"
    )
    return package_root, archive_path


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--date", required=True, help="Package date in YYYY-MM-DD")
    args = parser.parse_args()
    package_root, archive_path = build_package(args.date)
    print(f"package={package_root}")
    print(f"archive={archive_path}")
    print(f"sha256={sha256(archive_path)}")


if __name__ == "__main__":
    main()
